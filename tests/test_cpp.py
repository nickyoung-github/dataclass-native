def test_tree(headers):
    header = headers["schemas/tree.hpp"]
    # Forward declared, as recursive
    assert (
        "    struct Node;\n    struct Expr;\n    struct Leaf;\n    struct Wrapper;\n"
        in header
    )
    assert (
        "std::optional<dataclass_native::Indirect<Node>> next = std::nullopt;" in header
    )
    assert "std::vector<Node> children = std::vector<Node>{};" in header
    assert (
        "std::variant<dataclass_native::Indirect<Expr>, dataclass_native::Indirect<Leaf>> left{};"
        in header
    )
    assert "dataclass_native::Indirect<Expr> expr{};" in header


