def test_reserved_names(make_module):
    module = make_module(
        """
        from dataclasses import dataclass
        from dataclass_native import native

        @native
        @dataclass(frozen=True)
        class Bad:
            _Reserved: int
        """
    )
    with pytest.raises(SchemaError, match="reserved in C"):
        cpp.generate(build_schema([module]))


def test_cli_writes_only_changes(tmp_path, capsys):
    assert (
        main(["generate", "cpp", "--package", "schemas", "--out", str(tmp_path)]) == 0
    )
    written = capsys.readouterr().out.split()
    assert len(written) == 6

    assert (
        main(["generate", "cpp", "--package", "schemas", "--out", str(tmp_path)]) == 0
    )
    assert capsys.readouterr().out == ""


_PROGRAM = """
#include <cassert>
#include <iostream>

#include "schemas/sub/inner.hpp"
#include "schemas/trades.hpp"
#include "schemas/tree.hpp"

using namespace schemas;

int main()
{
    trades::Trade trade{.id = 1, .side = common::Side::SELL, .instrument = trades::Bond{.isin = "XS123"},
                        .counterparty = dataclass_native::Shared<common::Party>{common::Party{.name = "Acme"}}};
    assert(trade.price.amount == 100.0);
    assert(trade.price.currency == common::Currency::EUR);
    assert(trade.tags.size() == 3 && trade.tags[2] == "caf\\u00e9");
    assert(trade.labels.contains("y"));
    assert(std::get<0>(*trade.note) == "n/a");
    assert(std::chrono::year_month_day{trade.trade_date}.day() == std::chrono::day{27});

    // Shared values compare by value, and copies share
    trades::Trade copy = trade;
    assert(copy == trade);
    assert(std::get<0>(copy.counterparty).ptr() == std::get<0>(trade.counterparty).ptr());
    trades::Trade other = trade;
    other.counterparty = dataclass_native::Shared<common::Party>{common::Party{.name = "Acme"}};
    assert(other == trade);

    // Recursive types copy deeply
    tree::Node node{.value = 1, .next = tree::Node{.value = 2}, .children = {tree::Node{.value = 3}}};
    tree::Node node_copy = node;
    assert(node_copy == node);
    (*node_copy.next)->value = 4;
    assert(node_copy != node);
    assert((*node.next)->value == 2);

    tree::Expr expr{.op = "+", .left = tree::Leaf{.value = 1.0},
                    .right = tree::Expr{.op = "-", .left = tree::Leaf{.value = 2.0}}};
    tree::Expr expr_copy = expr;
    assert(expr_copy == expr);

    tree::Wrapper wrapper{};
    assert(!wrapper.expr);

    sub::inner::Order order{};
    assert(order.default_ == 0 && !order.new_ && order.total.currency == common::Currency::USD);

    std::cout << "ok" << std::endl;
    return 0;
}
"""


@pytest.mark.skipif(shutil.which("c++") is None, reason="No C++ compiler")
def test_headers_compile_and_run(tmp_path, headers):
    for relative, contents in headers.items():
        path = tmp_path / "include" / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(contents)

    source = tmp_path / "main.cpp"
    source.write_text(_PROGRAM)
    binary = tmp_path / "main"
    subprocess.run(
        [
            "c++",
            "-std=c++20",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-I",
            str(include_dir()),
            "-I",
            str(tmp_path / "include"),
            str(source),
            "-o",
            str(binary),
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    result = subprocess.run([str(binary)], check=True, capture_output=True, text=True)
    assert result.stdout.strip() == "ok"


